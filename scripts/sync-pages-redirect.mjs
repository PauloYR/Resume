// Generates the GitHub Pages redirects (docs/**/index.html) from the built pages, so the
// link preview (title, description, Open Graph, Twitter) always matches the real site.
// Usage: node scripts/sync-pages-redirect.mjs [--check]   (needs dist/, run `npm run build` first)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const TARGET = (
  process.env.PAGES_TARGET_URL || 'https://resume-delta-virid-65.vercel.app'
).replace(/\/$/, '');
const BUILT_ORIGIN = (process.env.SITE_URL || 'http://localhost:4321').replace(
  /\/$/,
  '',
);
// Each page gets its own redirect (docs/<slug>/index.html), so
// https://<user>.github.io/<repo>/sites previews and lands on the matching page.
const PAGES = [
  { slug: '', built: 'index.html' },
  { slug: 'sites', built: 'sites.html' },
  { slug: 'projetos', built: 'projetos.html' },
  { slug: 'curriculo', built: 'curriculo.html' },
];

const wanted = [
  /<title>[^<]*<\/title>/,
  /<meta name="description"[^>]*>/,
  /<meta property="og:[^"]+"[^>]*>/g,
  /<meta name="twitter:[^"]+"[^>]*>/g,
];

const render = ({ slug, built: file }) => {
  const built = readFileSync(`dist/${file}`, 'utf8');
  const tags = wanted.flatMap((re) => built.match(re) ?? []);
  if (!tags.length || !tags.some((t) => t.includes('og:image'))) {
    throw new Error(`no SEO tags found in dist/${file}; run \`npm run build\``);
  }
  const url = slug ? `${TARGET}/${slug}` : `${TARGET}/`;
  // Pages inside dist point at the build origin (or `/<file>.html`); send them to the live URL.
  const retarget = (tag) =>
    tag
      .replaceAll(`${BUILT_ORIGIN}/index.html`, `${TARGET}/`)
      .replaceAll(`${BUILT_ORIGIN}/${file}`, url)
      .replaceAll(BUILT_ORIGIN, TARGET);
  return {
    out: slug ? `docs/${slug}/index.html` : 'docs/index.html',
    html: `<!doctype html>
<!-- Generated by scripts/sync-pages-redirect.mjs. Do not edit by hand: run \`npm run pages:sync\`. -->
<html lang="pt-BR">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    ${tags.map(retarget).join('\n    ')}
    <meta http-equiv="refresh" content="0; url=${url}" />
    <link rel="canonical" href="${url}" />
    <script>
      location.replace('${url}');
    </script>
  </head>
  <body>
    <p>Redirecionando para <a href="${url}">${url.replace('https://', '')}</a>…</p>
  </body>
</html>
`,
  };
};

const check = process.argv.includes('--check');
let stale = false;
for (const { out, html } of PAGES.map(render)) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {}
    if (current !== html) {
      console.error(`${out} is out of date. Run: npm run pages:sync`);
      stale = true;
    } else {
      console.log(`${out} is up to date`);
    }
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, html);
    console.log(`${out} written`);
  }
}
if (stale) process.exit(1);
