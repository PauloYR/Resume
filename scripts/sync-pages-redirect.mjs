// Generates docs/index.html (GitHub Pages redirect) from the built home page, so the
// link preview (title, description, Open Graph, Twitter) always matches the real site.
// Usage: node scripts/sync-pages-redirect.mjs [--check]   (needs dist/, run `npm run build` first)
import { readFileSync, writeFileSync } from 'node:fs';

const TARGET = (
  process.env.PAGES_TARGET_URL || 'https://resume-delta-virid-65.vercel.app'
).replace(/\/$/, '');
const BUILT_ORIGIN = (process.env.SITE_URL || 'http://localhost:4321').replace(
  /\/$/,
  '',
);
const OUT = 'docs/index.html';

const built = readFileSync('dist/index.html', 'utf8');
const wanted = [
  /<title>[^<]*<\/title>/,
  /<meta name="description"[^>]*>/,
  /<meta property="og:[^"]+"[^>]*>/g,
  /<meta name="twitter:[^"]+"[^>]*>/g,
];
const tags = wanted.flatMap((re) => built.match(re) ?? []);
if (!tags.length || !tags.some((t) => t.includes('og:image'))) {
  throw new Error('no SEO tags found in dist/index.html; run `npm run build`');
}

// Pages inside dist point at the build origin (or `/index.html`); send them to the live site.
const retarget = (tag) =>
  tag
    .replaceAll(`${BUILT_ORIGIN}/index.html`, `${TARGET}/`)
    .replaceAll(BUILT_ORIGIN, TARGET);

const html = `<!doctype html>
<!-- Generated by scripts/sync-pages-redirect.mjs. Do not edit by hand: run \`npm run pages:sync\`. -->
<html lang="pt-BR">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    ${tags.map(retarget).join('\n    ')}
    <meta http-equiv="refresh" content="0; url=${TARGET}/" />
    <link rel="canonical" href="${TARGET}/" />
    <script>
      location.replace('${TARGET}/');
    </script>
  </head>
  <body>
    <p>Redirecionando para <a href="${TARGET}/">${TARGET.replace('https://', '')}</a>…</p>
  </body>
</html>
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== html) {
    console.error(`${OUT} is out of date. Run: npm run pages:sync`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, html);
  console.log(`${OUT} written`);
}
